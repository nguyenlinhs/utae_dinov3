class TemporallySharedBlock(nn.Module):
    """
    Applies 2D convolutions shared across all temporal frames of shape (B, T, C, H, W).
    """
    def __init__(self, pad_value=None):
        super(TemporallySharedBlock, self).__init__()
        self.out_shape = None
        self.pad_value = pad_value

    def smart_forward(self, input):
        if len(input.shape) == 4:
            return self.forward(input)
        b, t, c, h, w = input.shape
        out = input.view(b * t, c, h, w)
        out = self.forward(out)
        _, c_out, h_out, w_out = out.shape
        return out.view(b, t, c_out, h_out, w_out)


class ConvLayer(nn.Module):
    def __init__(
        self,
        nkernels,
        norm="batch",
        k=3,
        s=1,
        p=1,
        n_groups=4,
        last_relu=True,
        padding_mode="reflect",
    ):
        super(ConvLayer, self).__init__()
        layers = []
        if norm == "batch":
            nl = nn.BatchNorm2d
        elif norm == "instance":
            nl = nn.InstanceNorm2d
        elif norm == "group":
            nl = lambda num_feats: nn.GroupNorm(num_channels=num_feats, num_groups=n_groups)
        else:
            nl = None

        for i in range(len(nkernels) - 1):
            layers.append(
                nn.Conv2d(
                    in_channels=nkernels[i],
                    out_channels=nkernels[i + 1],
                    kernel_size=k,
                    padding=p,
                    stride=s,
                    padding_mode=padding_mode,
                )
            )
            if nl is not None:
                layers.append(nl(nkernels[i + 1]))

            if last_relu or (i < len(nkernels) - 2):
                layers.append(nn.ReLU())

        self.conv = nn.Sequential(*layers)

    def forward(self, input):
        return self.conv(input)


class ConvBlock(TemporallySharedBlock):
    def __init__(
        self,
        nkernels,
        pad_value=None,
        norm="batch",
        last_relu=True,
        padding_mode="reflect",
    ):
        super(ConvBlock, self).__init__(pad_value=pad_value)
        self.conv = ConvLayer(
            nkernels=nkernels,
            norm=norm,
            last_relu=last_relu,
            padding_mode=padding_mode,
        )

    def forward(self, input):
        return self.conv(input)


class DownConvBlock(TemporallySharedBlock):
    """(a) Spatial Down-convolution Block in Encoder."""
    def __init__(
        self,
        d_in,
        d_out,
        k=4,
        s=2,
        p=1,
        pad_value=None,
        norm="batch",
        padding_mode="reflect",
    ):
        super(DownConvBlock, self).__init__(pad_value=pad_value)
        self.down = ConvLayer(
            nkernels=[d_in, d_in],
            norm=norm,
            k=k,
            s=s,
            p=p,
            padding_mode=padding_mode,
        )
        self.conv1 = ConvLayer(
            nkernels=[d_in, d_out],
            norm=norm,
            padding_mode=padding_mode,
        )
        self.conv2 = ConvLayer(
            nkernels=[d_out, d_out],
            norm=norm,
            padding_mode=padding_mode,
        )

    def forward(self, input):
        out = self.down(input)
        out = self.conv1(out)
        out = out + self.conv2(out)
        return out


class UpConvBlock(nn.Module):
    """(b) Spatial Up-convolution Block in Decoder."""
    def __init__(
        self, d_in, d_out, k=4, s=2, p=1, norm="batch", d_skip=None, padding_mode="reflect"
    ):
        super(UpConvBlock, self).__init__()
        d = d_out if d_skip is None else d_skip
        self.skip_conv = nn.Sequential(
            nn.Conv2d(in_channels=d, out_channels=d, kernel_size=1),
            nn.BatchNorm2d(d),
            nn.ReLU(),
        )
        self.up = nn.Sequential(
            nn.ConvTranspose2d(
                in_channels=d_in, out_channels=d_out, kernel_size=k, stride=s, padding=p
            ),
            nn.BatchNorm2d(d_out),
            nn.ReLU(),
        )
        self.conv1 = ConvLayer(
            nkernels=[d_out + d, d_out], norm=norm, padding_mode=padding_mode
        )
        self.conv2 = ConvLayer(
            nkernels=[d_out, d_out], norm=norm, padding_mode=padding_mode
        )

    def forward(self, input, skip):
        out = self.up(input)
        if out.shape[-2:] != skip.shape[-2:]:
            out = F.interpolate(out, size=skip.shape[-2:], mode="bilinear", align_corners=False)
        out = torch.cat([out, self.skip_conv(skip)], dim=1)
        out = self.conv1(out)
        out = out + self.conv2(out)
        return out


class Temporal_Aggregator(nn.Module):
    """
    (c) Blockwise temporal weighted sum for skip connections.
    Uses attention masks generated by LTAE and bilinearly upsamples them (x2, x4, x8)
    to match the resolution of skip-connection feature maps.
    """
    def __init__(self, mode="att_group"):
        super(Temporal_Aggregator, self).__init__()
        self.mode = mode

    def forward(self, x, pad_mask=None, attn_mask=None):
        if self.mode == "att_group":
            n_heads, b, t, h, w = attn_mask.shape
            attn = attn_mask.contiguous().view(n_heads * b, t, h, w)
            if (h, w) != x.shape[-2:]:
                attn = F.interpolate(attn, size=x.shape[-2:], mode="bilinear", align_corners=False)

            attn = attn.view(n_heads, b, t, *x.shape[-2:])
            if pad_mask is not None and pad_mask.any():
                attn = attn * (~pad_mask).float()[None, :, :, None, None]

            out = torch.stack(x.chunk(n_heads, dim=2))  # (n_heads, B, T, C/n_heads, H, W)
            out = attn[:, :, :, None, :, :] * out
            out = out.sum(dim=2)                        # Sum over T -> (n_heads, B, C/n_heads, H, W)
            out = torch.cat([group for group in out], dim=1)  # Concat heads -> (B, C, H, W)
            return out
            
        elif self.mode == "att_mean":
            attn = attn_mask.mean(dim=0)
            if (attn.shape[-2], attn.shape[-1]) != x.shape[-2:]:
                attn = F.interpolate(attn, size=x.shape[-2:], mode="bilinear", align_corners=False)
            if pad_mask is not None and pad_mask.any():
                attn = attn * (~pad_mask).float()[:, :, None, None]
            return (x * attn[:, :, None, :, :]).sum(dim=1)
            
        elif self.mode == "mean":
            if pad_mask is not None and pad_mask.any():
                out = x * (~pad_mask).float()[:, :, None, None, None]
                return out.sum(dim=1) / (~pad_mask).sum(dim=1)[:, None, None, None]
            return x.mean(dim=1)
        else:
            raise ValueError(f"Unknown aggregation mode: {self.mode}")


class UTAE(nn.Module):
    """
    UTAE Model with DINO-v3 Encoder / Hybrid Architecture:
      - (a) Spatial Encoder: DINO-v3 ViT or ConvNeXt (or CNN fallback)
      - (c) Temporal Fusion with LTAE at bottleneck + Temporal Aggregator at skips
      - (b) Spatial Decoder with Up-convolutions and ConvBlock to produce output y(t)
    """
    def __init__(
        self,
        input_dim: int,
        encoder_widths=[64, 64, 64, 128],
        decoder_widths=[32, 32, 64, 128],
        out_conv=[32, 1],
        str_conv_k=4,
        str_conv_s=2,
        str_conv_p=1,
        agg_mode="att_group",
        encoder_norm="group",
        n_head=16,
        d_model=256,
        d_k=4,
        pad_value=0,
        padding_mode="reflect",
        encoder_type="dinov3",  # "dinov3" (ViT), "dinov3_convnext", or "cnn"
        dinov3_size="small",    # "small", "base", "large"
        dinov3_weights=None,    # Optional path to pretrained .pth weights
        freeze_encoder=False,
    ):
        super(UTAE, self).__init__()
        self.n_stages = len(encoder_widths)
        self.encoder_widths = encoder_widths
        self.decoder_widths = decoder_widths
        self.pad_value = pad_value
        self.encoder_type = encoder_type.lower()

        assert len(encoder_widths) == len(decoder_widths)
        assert encoder_widths[-1] == decoder_widths[-1]

        # (a) Spatial Encoder: DINO-v3 or CNN
        if self.encoder_type in ["dinov3", "dinov3_vit", "dinov3_convnext"]:
            arch = "convnext" if "convnext" in self.encoder_type else "vit"
            self.encoder = DINOv3Encoder(
                input_dim=input_dim,
                arch=arch,
                model_size=dinov3_size,
                out_channels=encoder_widths,
                pretrained_weights=dinov3_weights,
                freeze_backbone=freeze_encoder,
            )
            self.in_conv = None
            self.down_blocks = None
        else:
            # Baseline CNN Encoder
            self.encoder = None
            self.in_conv = ConvBlock(
                nkernels=[input_dim] + [encoder_widths[0], encoder_widths[0]],
                pad_value=pad_value,
                norm=encoder_norm,
                padding_mode=padding_mode,
            )
            self.down_blocks = nn.ModuleList(
                DownConvBlock(
                    d_in=encoder_widths[i],
                    d_out=encoder_widths[i + 1],
                    k=str_conv_k,
                    s=str_conv_s,
                    p=str_conv_p,
                    pad_value=pad_value,
                    norm=encoder_norm,
                    padding_mode=padding_mode,
                )
                for i in range(self.n_stages - 1)
            )

        # (c) Temporal Attention Encoder at Bottleneck
        self.temporal_encoder = LTAE2d(
            in_channels=encoder_widths[-1],
            d_model=d_model,
            n_head=n_head,
            mlp=[d_model, encoder_widths[-1]],
            return_att=True,
            d_k=d_k,
        )

        # (c) Skip Temporal Aggregator
        self.temporal_aggregator = Temporal_Aggregator(mode=agg_mode)

        # (b) Decoder Up-convolution stages
        self.up_blocks = nn.ModuleList(
            UpConvBlock(
                d_in=decoder_widths[i],
                d_out=decoder_widths[i - 1],
                d_skip=encoder_widths[i - 1],
                k=str_conv_k,
                s=str_conv_s,
                p=str_conv_p,
                norm="batch",
                padding_mode=padding_mode,
            )
            for i in range(self.n_stages - 1, 0, -1)
        )

        # (b) Final Output Convolution -> y(t)
        self.out_conv = ConvBlock(
            nkernels=[decoder_widths[0]] + out_conv, 
            padding_mode=padding_mode
        )

    def forward(self, input: torch.Tensor, batch_positions: torch.Tensor = None, return_att: bool = False):
        """
        Args:
            input (torch.Tensor): Shape (B, T, C, H, W)
            batch_positions (torch.Tensor, optional): Temporal positions (B, T), e.g. Day of Year.
            return_att (bool): Whether to return temporal attention maps.
        Returns:
            torch.Tensor: Output prediction y(t) logits of shape (B, out_channels, H, W)
        """
        B, T, C, H, W = input.shape
        if batch_positions is None:
            batch_positions = torch.arange(T, device=input.device).unsqueeze(0).repeat(B, 1)

        pad_mask = (input == self.pad_value).all(dim=-1).all(dim=-1).all(dim=-1)

        # 1. SPATIAL ENCODER (DINO-v3 or CNN)
        if self.encoder is not None:
            feature_maps = self.encoder.smart_forward(input)
        else:
            out = self.in_conv.smart_forward(input)
            feature_maps = [out]
            for i in range(self.n_stages - 1):
                out = self.down_blocks[i].smart_forward(feature_maps[-1])
                feature_maps.append(out)

        # 2. TEMPORAL ENCODER at Bottleneck (Fig. 8c)
        out, att = self.temporal_encoder(
            feature_maps[-1], batch_positions=batch_positions, pad_mask=pad_mask
        )

        # 3. SPATIAL DECODER with Skip Temporal Aggregation (Fig. 8b & 8c)
        for i in range(self.n_stages - 1):
            skip = self.temporal_aggregator(
                feature_maps[-(i + 2)], pad_mask=pad_mask, attn_mask=att
            )
            out = self.up_blocks[i](out, skip)

        # 4. FINAL PREDICTION LOGITS y(t)
        out = self.out_conv(out)
        if return_att:
            return out, att
        return out
